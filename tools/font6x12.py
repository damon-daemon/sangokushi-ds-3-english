FIXED_WIDTH = set('0123456789')   # keep digits monospaced so number columns line up
SPACE_WIDTH = 2

def _trim(rows):
    """Left-align a 6-column glyph; return (rows, advance width incl. 1px gap/shadow)."""
    cols = [c for c in range(6) if any((r + '.')[c] == '#' for r in rows)]
    if not cols:
        return rows, SPACE_WIDTH
    lo, hi = cols[0], cols[-1]
    return [(r + '.')[lo:6].ljust(6, '.') for r in rows], hi - lo + 2

def _bits_to_rows(b):
    v = int.from_bytes(b, 'big'); bits = bin(v)[2:].zfill(72)
    return [''.join('#' if bits[r * 6 + c] == '1' else '.' for c in range(6)) for r in range(12)]

def encode(rows):
    """12 rows x 6 columns, packed MSB-first into 9 bytes."""
    bits = ''.join(('#' if c == '#' else '.') for r in rows for c in (r + '.')[:6])
    v = int(''.join('1' if c == '#' else '0' for c in bits), 2)
    return v.to_bytes(9, 'big')

def table(game_glyph_bytes, vwf=True):
    """Glyphs and advance widths for 0x20-0x7F.

    game_glyph_bytes maps char -> 9 bytes from the ROM. Returns (96*9 glyph bytes,
    96 width bytes). With vwf, glyphs are left-aligned and widths proportional.
    """
    glyphs, widths = bytearray(), bytearray()
    for c in range(0x20, 0x80):
        ch = chr(c)
        rows = _bits_to_rows(game_glyph_bytes[ch]) if ch in game_glyph_bytes else GLYPHS[ch]
        w = 6
        if vwf and ch not in FIXED_WIDTH:
            rows, w = _trim(rows)
        glyphs += encode(rows); widths.append(w)
    return bytes(glyphs), bytes(widths)

assert set(GLYPHS) | set(GAME_GLYPHS) == {chr(c) for c in range(0x20, 0x80)}
